import AppKit
import SwiftUI

// Kopf-Aktionen des Chats für das Options-Menü des Controllers (Runde 5,
// Punkt 10): Angaben für das Menü und die Ausführung. Alles ruft dieselben
// Funktionen wie der Kopf der Einzelansicht, der Kachelkopf und das
// Kontextmenü. Ausgelagert, damit `AgentChatsView+Commands.swift` klein bleibt.

extension AgentChatsView {
    /// Ergänzt die Angaben für das Menü um die Kopf-Aktionen. Nur im
    /// Ereignis-Pfad aufrufen (Caches des Kontextmenüs, kein Datei-I/O).
    func addControllerHeadActions(to info: inout ControllerChatActionInfo, session: AgentChatSession) {
        let traits = sessionMenuTraits(for: session)
        let isRunning = terminalRegistry.controller(for: session.id)?.isRunning == true
        info.isRunning = isRunning
        let project = workspace.projects.first { $0.id == session.projectID }
        info.hasProject = !(project?.path.isEmpty ?? true)
        info.projectOpenTargetName = projectOpenTarget.label
        info.canRefreshTitle = session.titleIsAutoGenerated != false && session.externalSessionID != nil
            && !session.isTerminal
        info.isBackgroundChat = session.isBackgroundChat && session.hasBackgroundShortID
        info.canRestart = isRunning && traits.supportsRuntime && !session.isBackgroundChat
        info.canStopJob = traits.canStopSubagentJob
        info.hasTab = openTabIDs.contains(session.id)

        // Workspace: nur angelegte Workspaces (Projekt-Ansichten verwalten
        // ihre Mitglieder selbst), wie das Kontextmenü.
        let visible = isGridActive ? activeGridWorkspaceEntity : nil
        if let visible, visible.sourceProjectID == nil, visible.slotIndex(of: session.id) != nil {
            info.removableWorkspaceName = visible.name
        }
        let curated = windowStore.gridWorkspaces.filter { $0.sourceProjectID == nil && $0.slotIndex(of: session.id) == nil }
        info.addableWorkspaces = ControllerWorkspaceChoice.choices(
            from: curated, currentID: nil, status: { AgentSessionStatusCoordinator.shared.statusStore.status(for: $0) })
        let notesEnabled = AppPreferences.shared.isJarvisNotesEnabled
        info.notesAvailable = isGridActive && notesEnabled
        info.notesDefaultOpen = AppPreferences.shared.jarvisNotesDefaultOpen
        if isGridActive, notesEnabled, let visible, visible.slotIndex(of: session.id) != nil,
           JarvisNotesStore.shared.notes[session.id] != nil {
            info.tileNoteOpen = tileNoteIsOpen(session.id)
        }

        info.pendingAccountSwitchTarget = AccountSwitchCoordinator.shared.pending[session.id]?.targetName
        info.canUndoAccountSwitch = hasUndoableAccountMove
    }

    /// Ist die Notiz-Karte der Kachel gerade offen? Dieselbe Regel wie die
    /// Karte selbst (`JarvisNoteExpansion`).
    private func tileNoteIsOpen(_ sessionID: UUID) -> Bool {
        JarvisNoteExpansion.isOpen(
            hasNote: JarvisNotesStore.shared.notes[sessionID] != nil,
            override: JarvisNotesStore.shared.override(windowID: windowID, sessionID: sessionID),
            isFocused: selectedSessionID == sessionID,
            defaultOpen: AppPreferences.shared.jarvisNotesDefaultOpen)
    }

    /// Bestätigte Rückfrage aus `ControllerConfirmationDialog`.
    func performControllerConfirmed(_ pending: ControllerConfirmations.Pending) {
        switch pending.kind {
        case .backgroundStop:
            guard let session = workspace.sessions.first(where: { $0.id == pending.sessionID }),
                  session.hasBackgroundShortID else { return }
            performBackgroundLifecycle(.stop, on: session)
        case .stopJob:
            // Derselbe Weg wie „Job stoppen“ im Kontextmenü (`agent stop`).
            guard let pid = jobRuntimeModel.snapshotsBySessionID[pending.sessionID]?.supervisorPid else { return }
            _ = kill(pid, SIGTERM)
            AgentJobWorkspaceSync.shared.requestSync(reason: "controller-stop")
        }
    }

    /// Führt eine Kopf-Aktion aus. `false`, wenn sie für den Chat nicht (mehr)
    /// passt — der Controller meldet „geht nicht“.
    func performControllerChatCommand(_ command: AgentChatsCommand) -> Bool {
        func session(_ id: UUID) -> AgentChatSession? { workspace.sessions.first { $0.id == id } }
        func project(of id: UUID) -> AgentProject? {
            guard let session = session(id) else { return nil }
            return workspace.projects.first { $0.id == session.projectID && !$0.path.isEmpty }
        }
        switch command {
        case .openProjectOfChat(let id):
            guard let project = project(of: id) else { return false }
            openProject(project, in: projectOpenTarget)
            return true
        case .revealProjectInFinder(let id):
            guard let project = project(of: id) else { return false }
            NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: project.path)])
            return true
        case .refreshChatTitle(let id):
            guard let session = session(id), session.externalSessionID != nil else { return false }
            forceAutoNameSession(session)
            return true
        case .restartChat(let id):
            // Wie „Neu starten“ im Kontextmenü; die Rückfrage der Ansicht bleibt.
            guard terminalRegistry.controller(for: id)?.isRunning == true else { return false }
            let request = AgentSessionActionRequest(sessionID: id, kind: .restart)
            guard selectedSessionID != id else {
                sessionActionRequest = request
                return true
            }
            selectedSessionID = id
            multiSelection = []
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.2) { sessionActionRequest = request }
            return true
        case .toggleTileNote(let id):
            guard isGridActive, JarvisNotesStore.shared.notes[id] != nil else { return false }
            JarvisNotesStore.shared.setOverride(!tileNoteIsOpen(id), windowID: windowID, sessionID: id)
            return true
        case .toggleNotes:
            guard isGridActive else { return false }
            JarvisNotesShortcut.toggleDefault(windowID: windowID)
            return true
        case .removeChatFromWorkspace(let id):
            guard isGridActive, let entity = activeGridWorkspaceEntity, entity.sourceProjectID == nil,
                  entity.slotIndex(of: id) != nil else { return false }
            removeSessionFromWorkspace(id, workspaceID: entity.id)
            return true
        case .addChatToWorkspace(let id, let workspaceID):
            guard session(id) != nil, let entity = windowStore.gridWorkspace(id: workspaceID),
                  entity.slotIndex(of: id) == nil else { return false }
            addSessionToWorkspace(id, workspaceID: workspaceID)
            return true
        case .moveChatToNewWindow(let id):
            guard let session = session(id), openTabIDs.contains(id) else { return false }
            moveSingleTabToNewWindow(session)
            return true
        case .backgroundLogs(let id):
            guard let session = session(id), session.hasBackgroundShortID else { return false }
            showBackgroundLogs(for: session)
            return true
        case .backgroundStop(let id):
            // Mit Rückfrage (Review Runde 5, Befund 7); bestätigt per Kreuz.
            guard let session = session(id), session.hasBackgroundShortID,
                  !pendingLifecycleSessions.contains(id) else { return false }
            ControllerConfirmations.shared.pending[windowID] = .init(kind: .backgroundStop, sessionID: id, title: session.title)
            return true
        case .backgroundRespawn(let id):
            guard let session = session(id), session.hasBackgroundShortID,
                  !pendingLifecycleSessions.contains(id) else { return false }
            performBackgroundLifecycle(.respawn, on: session)
            return true
        case .stopSubagentJob(let id):
            guard let session = session(id), jobRuntimeModel.snapshotsBySessionID[id]?.supervisorPid != nil else {
                return false
            }
            ControllerConfirmations.shared.pending[windowID] = .init(kind: .stopJob, sessionID: id, title: session.title)
            return true
        case .cancelAccountSwitch(let id):
            guard AccountSwitchCoordinator.shared.pending[id] != nil else { return false }
            AccountSwitchCoordinator.shared.cancel(sessionID: id)
            return true
        case .undoLastAccountSwitch:
            guard hasUndoableAccountMove else { return false }
            undoLastAccountMove()
            return true
        default:
            return false
        }
    }
}
