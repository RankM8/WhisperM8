import AppKit
import XCTest
@testable import WhisperM8

@MainActor
final class ClipboardMonitorTests: XCTestCase {
    private var directory: URL!
    private var pasteboard: NSPasteboard!
    private var store: ClipboardHistoryStore!
    private var currentSettings = ClipboardSettings(enabled: true)
    private var frontmost: (bundleID: String?, name: String?) = ("com.apple.Safari", "Safari")

    override func setUp() async throws {
        directory = FileManager.default.temporaryDirectory
            .appendingPathComponent("clipboard-monitor-\(UUID().uuidString)", isDirectory: true)
        pasteboard = NSPasteboard(name: NSPasteboard.Name("whisperm8-test-\(UUID().uuidString)"))
        store = ClipboardHistoryStore(directory: directory, debounceSeconds: 0.01)
        currentSettings = ClipboardSettings(enabled: true)
        frontmost = ("com.apple.Safari", "Safari")
    }

    override func tearDown() async throws {
        pasteboard.releaseGlobally()
        try? FileManager.default.removeItem(at: directory)
    }

    private func makeMonitor() -> ClipboardMonitor {
        ClipboardMonitor(
            store: store, pasteboard: pasteboard, interval: 0.5,
            settings: { [unowned self] in self.currentSettings },
            frontmostApp: { [unowned self] in self.frontmost }
        )
    }

    private func copy(_ text: String, extraTypes: [String] = []) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in extraTypes { item.setData(Data([1]), forType: NSPasteboard.PasteboardType(type)) }
        pasteboard.writeObjects([item])
    }

    /// Wartet auf Lesen (Hintergrund) und Speichern (Store-Queue).
    private func entries(_ monitor: ClipboardMonitor) async -> [ClipboardEntry] {
        await monitor.waitForReads()
        store.waitUntilIdle()
        return store.snapshot()
    }

    private func pngData() -> Data {
        let rep = NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: 4, pixelsHigh: 3, bitsPerSample: 8, samplesPerPixel: 4,
            hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
        )!
        return rep.representation(using: .png, properties: [:])!
    }

    func testStoresNewCopyWithSourceApp() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        copy("hello")
        monitor.tick()
        let result = await entries(monitor)
        XCTAssertEqual(result.map(\.preview), ["hello"])
        XCTAssertEqual(result.first?.sourceName, "Safari")
        XCTAssertEqual(result.first?.sourceBundleID, "com.apple.Safari")
    }

    func testIgnoresContentAlreadyPresentWhenStarted() async {
        copy("before")
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        monitor.tick()
        let result = await entries(monitor)
        XCTAssertTrue(result.isEmpty)
    }

    func testSameChangeCountIsReadOnlyOnce() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        copy("once")
        monitor.tick(); monitor.tick(); monitor.tick()
        let result = await entries(monitor)
        XCTAssertEqual(result.count, 1)
    }

    func testSkipsConfidentialAndExcludedApp() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        copy("secret", extraTypes: ["org.nspasteboard.ConcealedType"])
        monitor.tick()
        frontmost = ("com.1password.1password", "1Password")
        copy("from password manager")
        monitor.tick()
        let result = await entries(monitor)
        XCTAssertTrue(result.isEmpty)
        XCTAssertEqual(monitor.skippedCount, 2)
    }

    func testSkipsTransientAndLegacyPasswordManagerTypes() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        for type in ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"] {
            copy("value-\(type)", extraTypes: [type])
            monitor.tick()
        }
        let result = await entries(monitor)
        XCTAssertTrue(result.isEmpty)
        XCTAssertEqual(monitor.skippedCount, 3)
    }

    func testSkipsWhenDisabledOrPaused() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        currentSettings.paused = true
        copy("paused")
        monitor.tick()
        currentSettings.paused = false
        currentSettings.enabled = false
        copy("disabled")
        monitor.tick()
        let result = await entries(monitor)
        XCTAssertTrue(result.isEmpty)
    }

    func testOwnMarkerIsIgnored() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        copy("from our own paste", extraTypes: [ClipboardInternalMarker.typeName])
        monitor.tick()
        let result = await entries(monitor)
        XCTAssertTrue(result.isEmpty)
    }

    func testClaimedWriteIsSkippedButRealCopyRightAfterIsKept() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        copy("dictation result")
        ClipboardInternalWrites.claim(pasteboard)
        monitor.tick()
        // Der User kopiert direkt danach.
        copy("real copy")
        monitor.tick()
        let result = await entries(monitor)
        XCTAssertEqual(result.map(\.preview), ["real copy"])
    }

    func testRealCopyBetweenTwoTicksAfterOwnWriteIsKept() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        copy("ours")
        ClipboardInternalWrites.claim(pasteboard)
        // Eigener Stand und echte Kopie im selben Takt: der echte gewinnt.
        copy("real copy in the same half second")
        monitor.tick()
        let result = await entries(monitor)
        XCTAssertEqual(result.map(\.preview), ["real copy in the same half second"])
    }

    func testContextCaptureBracketWaitsThenSkipsItsOwnChanges() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        ClipboardInternalWrites.begin()
        let baseline = pasteboard.changeCount
        copy("selection copied by Cmd+C")   // schreibt die fremde App
        monitor.tick()                       // Klammer offen: abwarten
        ClipboardInternalWrites.claim(count: baseline + 1, through: pasteboard.changeCount, on: pasteboard)
        copy("restored snapshot")
        ClipboardInternalWrites.claim(pasteboard)
        ClipboardInternalWrites.end()
        monitor.tick()
        var result = await entries(monitor)
        XCTAssertTrue(result.isEmpty)
        copy("real copy")
        monitor.tick()
        result = await entries(monitor)
        XCTAssertEqual(result.map(\.preview), ["real copy"])
    }

    func testRealCopyInsideContextBracketIsKept() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        ClipboardInternalWrites.begin()
        let baseline = pasteboard.changeCount
        copy("selection copied by Cmd+C")
        ClipboardInternalWrites.claim(count: baseline + 1, through: pasteboard.changeCount, on: pasteboard)
        // Der User kopiert, bevor zurückgeschrieben wird: die Erfassung lässt
        // seine Kopie stehen (kein Zurückschreiben) und beansprucht sie nicht.
        copy("user copy during capture")
        ClipboardInternalWrites.end()
        monitor.tick()
        let result = await entries(monitor)
        XCTAssertEqual(result.map(\.preview), ["user copy during capture"])
    }

    func testDuplicateCopyMovesEntryUp() async {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        copy("a"); monitor.tick(); _ = await entries(monitor)
        copy("b"); monitor.tick(); _ = await entries(monitor)
        copy("a"); monitor.tick()
        let result = await entries(monitor)
        XCTAssertEqual(ClipboardHistoryCore.chronological(result).map(\.preview), ["a", "b"])
    }

    func testCapturesRichTextAlongsidePlain() async throws {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString("bold", forType: .string)
        item.setData(Data("{\\rtf1 bold}".utf8), forType: .rtf)
        item.setData(Data("<b>bold</b>".utf8), forType: .html)
        pasteboard.writeObjects([item])
        monitor.tick()
        let captured = await entries(monitor)
        let entry = try XCTUnwrap(captured.first)
        XCTAssertNotNil(entry.rtfFile)
        XCTAssertNotNil(entry.htmlFile)
        XCTAssertNil(entry.archiveFile, "Nur Standardtypen: kein Archiv nötig")
    }

    func testTableWithImageKeepsEveryTypeForPasting() async throws {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        let png = pngData()
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString("A1\tB1", forType: .string)
        item.setData(Data("<table><tr><td>A1</td></tr></table>".utf8), forType: .html)
        item.setData(png, forType: .png)
        item.setData(Data([7, 7, 7]), forType: NSPasteboard.PasteboardType("com.microsoft.Excel.sheet"))
        pasteboard.writeObjects([item])
        monitor.tick()
        let captured = await entries(monitor)
        let entry = try XCTUnwrap(captured.first)
        XCTAssertEqual(entry.kind, .text)
        XCTAssertEqual(entry.preview, "A1\tB1")
        XCTAssertNotNil(entry.archiveFile)

        // Zurückschreiben bringt alle Typen wieder, Text plus Bild plus App-Format.
        let payload = try XCTUnwrap(ClipboardRestore.payload(for: entry, plain: false, directory: directory))
        guard case .items(let items) = payload else { return XCTFail("Einträge erwartet") }
        let types = Set(items.flatMap { $0.map(\.type) })
        XCTAssertTrue(types.isSuperset(of: ["public.utf8-plain-text", "public.html", "public.png", "com.microsoft.Excel.sheet"]))
        XCTAssertEqual(items.first?.first { $0.type == "public.png" }?.data, png)

        // Reiner Text (⌥↩) nur mit dem Text.
        XCTAssertEqual(
            ClipboardRestore.payload(for: entry, plain: true, directory: directory),
            .items([[ClipboardRepresentation(type: "public.utf8-plain-text", data: Data("A1\tB1".utf8))]])
        )
    }

    func testRestoreWritesMarkedAndClaimedSoTheMonitorSkipsIt() async throws {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        copy("original"); monitor.tick()
        let captured = await entries(monitor)
        let entry = try XCTUnwrap(captured.first)
        copy("something else"); monitor.tick()
        _ = await entries(monitor)
        let payload = try XCTUnwrap(ClipboardRestore.payload(for: entry, plain: false, directory: directory))
        XCTAssertTrue(ClipboardRestore.write(payload, to: pasteboard))
        XCTAssertEqual(pasteboard.string(forType: .string), "original")
        XCTAssertTrue(pasteboard.types?.map(\.rawValue).contains(ClipboardInternalMarker.typeName) ?? false)
        let before = monitor.skippedCount
        monitor.tick()
        XCTAssertEqual(monitor.skippedCount, before + 1)
        let result = await entries(monitor)
        XCTAssertEqual(result.count, 2)
    }

    func testFileURLsAreCapturedAsFiles() async throws {
        let monitor = makeMonitor()
        monitor.start(); monitor.stop()
        let file = directory.appendingPathComponent("x.txt")
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        try Data("x".utf8).write(to: file)
        pasteboard.clearContents()
        pasteboard.writeObjects([file as NSURL])
        monitor.tick()
        let captured = await entries(monitor)
        let entry = try XCTUnwrap(captured.first)
        XCTAssertEqual(entry.kind, .files)
        XCTAssertEqual(entry.filePaths?.first.map { URL(fileURLWithPath: $0).lastPathComponent }, "x.txt")
        XCTAssertNil(entry.archiveFile)
    }

    func testStartAndStopDoNotStackTimers() {
        let monitor = makeMonitor()
        XCTAssertFalse(monitor.isRunning)
        monitor.start(); monitor.start()
        XCTAssertTrue(monitor.isRunning)
        monitor.stop()
        XCTAssertFalse(monitor.isRunning)
        monitor.stop()
        XCTAssertFalse(monitor.isRunning)
    }
}
