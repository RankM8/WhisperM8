import Foundation
import XCTest
@testable import WhisperM8

final class AgentSessionAutoNamerTests: XCTestCase {
    func testAgentHeadlessCLIReturnsStdout() async throws {
        let output = try await AgentHeadlessCLI(timeout: 2).run(
            executable: URL(fileURLWithPath: "/bin/echo"),
            arguments: ["hello"],
            environment: [:]
        )

        XCTAssertEqual(output.trimmingCharacters(in: .whitespacesAndNewlines), "hello")
    }

    func testAgentHeadlessCLIReportsNonZeroExit() async throws {
        do {
            _ = try await AgentHeadlessCLI(timeout: 2).run(
                executable: URL(fileURLWithPath: "/bin/sh"),
                arguments: ["-c", "echo nope >&2; exit 7"],
                environment: [:]
            )
            XCTFail("Expected non-zero exit")
        } catch AgentHeadlessCLIError.nonZeroExit(let code, let stderr, _) {
            XCTAssertEqual(code, 7)
            XCTAssertTrue(stderr.contains("nope"))
        }
    }

    func testAgentHeadlessCLITimesOut() async throws {
        do {
            _ = try await AgentHeadlessCLI(timeout: 0.05).run(
                executable: URL(fileURLWithPath: "/bin/sleep"),
                arguments: ["2"],
                environment: [:]
            )
            XCTFail("Expected timeout")
        } catch AgentHeadlessCLIError.timedOut {
            // Expected.
        }
    }

    func testAgentHeadlessCLIHandlesOutputLargerThanPipeBuffer() async throws {
        // Regression Review-Befund 2026-07-19: Ausgaben > 64-KB-Pipe-Puffer
        // liessen den Prozess beim Schreiben blockieren (Read erst im
        // terminationHandler) → Timeout statt Ergebnis.
        let output = try await AgentHeadlessCLI(timeout: 10).run(
            executable: URL(fileURLWithPath: "/bin/sh"),
            arguments: ["-c", "yes a | head -c 300000"],
            environment: [:]
        )
        XCTAssertEqual(output.utf8.count, 300_000)
    }

    func testAgentHeadlessCLIDoesNotHangOnStdinReaders() async throws {
        // stdin ist /dev/null: ein Befehl, der von stdin liest (z. B. ein
        // Bestaetigungs-Prompt), bekommt sofort EOF statt ewig zu warten.
        let output = try await AgentHeadlessCLI(timeout: 5).run(
            executable: URL(fileURLWithPath: "/bin/sh"),
            arguments: ["-c", "cat; echo done"],
            environment: [:]
        )
        XCTAssertEqual(output.trimmingCharacters(in: .whitespacesAndNewlines), "done")
    }

