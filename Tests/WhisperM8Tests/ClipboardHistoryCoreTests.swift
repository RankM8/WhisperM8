import XCTest
@testable import WhisperM8

final class ClipboardHistoryCoreTests: XCTestCase {
    private func entry(
        _ id: String, text: String = "", at seconds: TimeInterval, pinned: Bool = false,
        kind: ClipboardEntry.Kind = .text, app: String? = nil, hash: String? = nil
    ) -> ClipboardEntry {
        ClipboardEntry(
            id: id, kind: kind, createdAt: Date(timeIntervalSince1970: seconds),
            lastCopiedAt: Date(timeIntervalSince1970: seconds), copyCount: 1, isPinned: pinned,
            sourceBundleID: nil, sourceName: app, contentHash: hash ?? ClipboardEntry.hash(text: text),
            preview: ClipboardEntry.makePreview(from: text), text: text
        )
    }

    // MARK: Erfassen

    func testDecideStoresPlainContent() {
        XCTAssertEqual(
            ClipboardHistoryCore.decide(enabled: true, paused: false, isInternalWrite: false,
                                        types: ["public.utf8-plain-text"], sourceBundleID: "com.apple.Safari", excludedApps: []),
            .store
        )
    }

    func testDecideSkipsDisabledPausedAndInternal() {
        func decide(enabled: Bool = true, paused: Bool = false, isInternal: Bool = false, types: [String] = []) -> ClipboardHistoryCore.CaptureDecision {
            ClipboardHistoryCore.decide(enabled: enabled, paused: paused, isInternalWrite: isInternal,
                                        types: types, sourceBundleID: nil, excludedApps: [])
        }
        XCTAssertEqual(decide(enabled: false), .skip(.disabled))
        XCTAssertEqual(decide(paused: true), .skip(.paused))
        XCTAssertEqual(decide(isInternal: true), .skip(.internalWrite))
        XCTAssertEqual(decide(types: [ClipboardInternalMarker.typeName]), .skip(.internalWrite))
    }

    func testDecideNeverStoresConfidentialTypes() {
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertEqual(
                ClipboardHistoryCore.decide(enabled: true, paused: false, isInternalWrite: false,
                                            types: ["public.utf8-plain-text", type], sourceBundleID: nil, excludedApps: []),
                .skip(.confidential), type
            )
        }
    }

    func testDecideHonoursExcludedAppsCaseInsensitively() {
        XCTAssertEqual(
            ClipboardHistoryCore.decide(enabled: true, paused: false, isInternalWrite: false, types: [],
                                        sourceBundleID: "COM.1Password.1password", excludedApps: ["com.1password.1password"]),
            .skip(.excludedApp)
        )
        XCTAssertEqual(
            ClipboardHistoryCore.decide(enabled: true, paused: false, isInternalWrite: false, types: [],
                                        sourceBundleID: "com.apple.Safari", excludedApps: ["com.1password.1password"]),
            .store
        )
    }

    // MARK: Duplikate

    func testInsertPutsNewEntryOnTop() {
        let result = ClipboardHistoryCore.insert(entry("b", text: "two", at: 20), into: [entry("a", text: "one", at: 10)])
        XCTAssertFalse(result.merged)
        XCTAssertEqual(result.entries.map(\.id), ["b", "a"])
    }

    func testInsertMergesDuplicateAndKeepsPinAndId() {
        var old = entry("a", text: "same", at: 10, pinned: true)
        old.sourceName = "Safari"
        let other = entry("c", text: "other", at: 15)
        var fresh = entry("n", text: "same", at: 30)
        fresh.sourceName = "Xcode"
        fresh.sourceBundleID = "com.apple.dt.Xcode"
        fresh.rtfFile = "n.rtf"
        let result = ClipboardHistoryCore.insert(fresh, into: [other, old])
        XCTAssertTrue(result.merged)
        XCTAssertEqual(result.entries.map(\.id), ["a", "c"])
        let merged = result.entries[0]
        XCTAssertTrue(merged.isPinned)
        XCTAssertEqual(merged.copyCount, 2)
        XCTAssertEqual(merged.createdAt, Date(timeIntervalSince1970: 10))
        XCTAssertEqual(merged.lastCopiedAt, Date(timeIntervalSince1970: 30))
        XCTAssertEqual(merged.sourceName, "Xcode")
        XCTAssertEqual(result.discardedBlobs, ["n.rtf"])
    }

    func testSameHashButOtherKindIsNotADuplicate() {
        let text = entry("a", text: "x", at: 10, hash: "h")
        let image = entry("b", at: 20, kind: .image, hash: "h")
        XCTAssertFalse(ClipboardHistoryCore.insert(image, into: [text]).merged)
    }

    // MARK: Kürzen

    func testTrimKeepsNewestUnpinnedAndAllPinned() {
        let entries = [
            entry("p-old", text: "p", at: 1, pinned: true),
            entry("a", text: "a", at: 10), entry("b", text: "b", at: 20),
            entry("c", text: "c", at: 30), entry("d", text: "d", at: 40),
        ]
        let result = ClipboardHistoryCore.trim(entries, maxUnpinned: 2)
        XCTAssertEqual(Set(result.kept.map(\.id)), ["p-old", "c", "d"])
        XCTAssertEqual(Set(result.removed.map(\.id)), ["a", "b"])
    }

    func testTrimLeavesSmallHistoryAlone() {
        let entries = [entry("a", text: "a", at: 1), entry("b", text: "b", at: 2)]
        let result = ClipboardHistoryCore.trim(entries, maxUnpinned: 200)
        XCTAssertEqual(result.kept.count, 2)
        XCTAssertTrue(result.removed.isEmpty)
    }

    // MARK: Reihenfolge und Nummern

    func testDisplayOrderPutsPinnedFirstNewestFirst() {
        let entries = [
            entry("a", text: "a", at: 10), entry("p1", text: "p1", at: 5, pinned: true),
            entry("b", text: "b", at: 20), entry("p2", text: "p2", at: 8, pinned: true),
        ]
        XCTAssertEqual(ClipboardHistoryCore.displayOrder(entries).map(\.id), ["p2", "p1", "b", "a"])
        XCTAssertEqual(ClipboardHistoryCore.chronological(entries).map(\.id), ["b", "a", "p2", "p1"])
    }

    func testResolveByNumberIdAndPrefix() throws {
        let entries = [
            entry("1111aaaa-0000", text: "old", at: 10),
            entry("2222bbbb-0000", text: "new", at: 20),
        ]
        XCTAssertEqual(try ClipboardHistoryCore.resolve("1", in: entries).get().id, "2222bbbb-0000")
        XCTAssertEqual(try ClipboardHistoryCore.resolve("2", in: entries).get().id, "1111aaaa-0000")
        XCTAssertEqual(try ClipboardHistoryCore.resolve("1111aaaa-0000", in: entries).get().id, "1111aaaa-0000")
        XCTAssertEqual(try ClipboardHistoryCore.resolve("2222", in: entries).get().id, "2222bbbb-0000")
    }

    func testResolveErrors() {
        let entries = [entry("abcd1111", text: "a", at: 1), entry("abcd2222", text: "b", at: 2)]
        XCTAssertEqual(ClipboardHistoryCore.resolve("3", in: entries).failure, .outOfRange(3, 2))
        XCTAssertEqual(ClipboardHistoryCore.resolve("0", in: entries).failure, .outOfRange(0, 2))
        XCTAssertEqual(ClipboardHistoryCore.resolve("abcd", in: entries).failure, .ambiguous("abcd"))
        XCTAssertEqual(ClipboardHistoryCore.resolve("zzzzzz", in: entries).failure, .notFound("zzzzzz"))
        XCTAssertEqual(ClipboardHistoryCore.resolve("ab", in: entries).failure, .notFound("ab"))
    }

    // MARK: Suche

    func testSearchIsCaseAndDiacriticInsensitiveAndNeedsAllTerms() {
        let entries = [
            entry("a", text: "Grüße an das Team", at: 10),
            entry("b", text: "Team Meeting um 10", at: 20),
            entry("c", text: "etwas anderes", at: 30),
        ]
        XCTAssertEqual(ClipboardHistoryCore.search(entries, query: "grusse").map(\.id), ["a"])
        XCTAssertEqual(Set(ClipboardHistoryCore.search(entries, query: "TEAM").map(\.id)), ["a", "b"])
        XCTAssertEqual(ClipboardHistoryCore.search(entries, query: "team meeting").map(\.id), ["b"])
        XCTAssertTrue(ClipboardHistoryCore.search(entries, query: "team zzz").isEmpty)
    }

    func testSearchRanksEarlierAndWordStartMatchesHigher() {
        let entries = [
            entry("late", text: "irgendwas mit foo am Ende", at: 30),
            entry("start", text: "foo am Anfang", at: 10),
        ]
        XCTAssertEqual(ClipboardHistoryCore.search(entries, query: "foo").map(\.id), ["start", "late"])
    }

    func testEmptyQueryReturnsDisplayOrder() {
        let entries = [entry("a", text: "a", at: 1), entry("p", text: "p", at: 0, pinned: true)]
        XCTAssertEqual(ClipboardHistoryCore.search(entries, query: "  ").map(\.id), ["p", "a"])
    }

    func testSearchFindsSourceAppAndFilePaths() {
        var files = entry("f", at: 5, kind: .files)
        files.filePaths = ["/Users/demo/Angebot.pdf"]
        files.preview = "Angebot.pdf"
        let text = entry("t", text: "x", at: 6, app: "Safari")
        XCTAssertEqual(ClipboardHistoryCore.search([files, text], query: "angebot").map(\.id), ["f"])
        XCTAssertEqual(ClipboardHistoryCore.search([files, text], query: "safari").map(\.id), ["t"])
    }

    func testPreviewCollapsesWhitespaceAndTruncates() {
        XCTAssertEqual(ClipboardEntry.makePreview(from: "  a\n\n  b  \n"), "a b")
        let long = String(repeating: "x", count: 500)
        XCTAssertEqual(ClipboardEntry.makePreview(from: long).count, ClipboardEntry.previewLimit + 1)
    }
}

private extension Result {
    var failure: Failure? {
        if case .failure(let error) = self { return error }
        return nil
    }
}
